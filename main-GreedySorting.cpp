#include <iostream>
#include <string>
#include <vector>
#include <algorithm>

using namespace std;

/**
 * ============================================================================
 * Решение 2: Greedy подход със сортиране (Greedy with Sorting)
 * ============================================================================
 * 
 * АЛГОРИТЪМ:
 * ----------
 * 1. Намираме всички задължителни станции (съдържащи ключовия низ)
 * 2. Сортираме ги по индекс (в случай че не са подредени)
 * 3. Greedy избор: посещаваме минималния брой станции
 * 
 * СЛОЖНОСТ:
 * ---------
 * - Време: O(T * (N * M + K * log(K)))
 *   където:
 *     T = брой запитвания
 *     N = брой станции
 *     M = средна дължина на име на станция (за string::find)
 *     K = брой задължителни станции
 * 
 * - Памет: O(N * M + K) за имената и списъка със задължителни
 * 
 * GREEDY ОБОСНОВКА:
 * -----------------
 * Тъй като можем да се движим само напред и ТРЯБВА да посетим всички
 * задължителни станции, оптималният път е да посетим точно:
 * - Началната станция (1)
 * - Всички задължителни станции (в реда им на появяване)
 * - Крайната станция (N)
 * 
 * Сортирането гарантира, че обработваме станциите в правилен ред.
 * 
 * ============================================================================
 */

int solve() {
    int n;
    cin >> n;
    
    vector<string> stations(n);
    for (int i = 0; i < n; i++) {
        cin >> stations[i];
    }
    
    string key;
    cin >> key;
    
    if (n == 1) return 1;
    
    vector<int> mandatory;
    for (int i = 1; i < n - 1; i++) {
        if (stations[i].find(key) != string::npos) {
            mandatory.push_back(i);
        }
    }
    
    sort(mandatory.begin(), mandatory.end());
    
    return 2 + mandatory.size();
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    
    int t;
    cin >> t;
    
    while (t--) {
        cout << solve() << "\n";
    }
    
    return 0;
}
