#include <iostream>
#include <string>

using namespace std;

/**
 * ============================================================================
 * Решение 3: Оптимален подход (Optimal Approach)
 * ============================================================================
 * 
 * АЛГОРИТЪМ:
 * ----------
 * Директно броене на задължителните станции в един проход.
 * Използваме вградената функция string::find() за ефективно търсене.
 * 
 * СЛОЖНОСТ:
 * ---------
 * - Време: O(T * N * M)
 *   където:
 *     T = брой запитвания
 *     N = брой станции
 *     M = средна дължина на име на станция
 * 
 *   Забележка: string::find() използва оптимизиран алгоритъм
 *   (често Boyer-Moore или подобен в STL имплементациите)
 * 
 * - Памет: O(N * M) за съхранение на имената
 *   Може да се намали до O(M) ако обработваме станция по станция
 * 
 * ЗАЩО Е ОПТИМАЛЕН:
 * -----------------
 * 1. Няма излишно сортиране (за разлика от Greedy подхода)
 * 2. Използва оптимизирана библиотечна функция за търсене
 * 3. Един проход през данните - O(N)
 * 4. Минимална памет - не пазим списък със задължителни станции
 * 
 * КОРЕКТНОСТ:
 * -----------
 * Минималният път от станция 1 до станция N включва:
 * - Станция 1 (начална) - задължително
 * - Станция N (крайна) - задължително  
 * - Всяка станция между тях, която съдържа ключа - задължително
 * 
 * Тъй като можем да "прескачаме" незадължителни станции,
 * отговорът е точно: 2 + (брой задължителни между 1 и N)
 * 
 * ============================================================================
 */

bool containsKey(const string& station, const string& key) {
    return station.find(key) != string::npos;
}

int solve() {
    int n;
    cin >> n;
    
    string stations[n];
    for (int i = 0; i < n; i++) {
        cin >> stations[i];
    }
    
    string key;
    cin >> key;
    
    if (n == 1) {
        return 1;
    }
    
    int count = 2;
    
    for (int i = 1; i < n - 1; i++) {
        if (containsKey(stations[i], key)) {
            count++;
        }
    }
    
    return count;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    
    int t;
    cin >> t;
    
    while (t--) {
        cout << solve() << "\n";
    }
    
    return 0;
}
